import { CdpBrowser, Page, sleep } from "./cdp.mjs";
const b = await CdpBrowser.launch({ port: 9335 });
const p = await Page.create(b);
await p.setViewport(1440, 900);
await p.goto("http://127.0.0.1:5199/");
await p.waitFor("document.querySelector('#composer-mode-switch .mode-btn')", { timeout: 40000 });
await p.click("#composer-mode-switch .mode-btn");
await p.waitFor("document.querySelector('[data-im=\"board\"]')", { timeout: 30000 });
await sleep(1500);
const before = await p.count('[data-im="card"]');
await p.click('[data-im="add-menu"]');
await p.waitFor("document.querySelector('[data-im=\"add-menu-list\"]')");
await p.click('[data-im="add-text"]');
await p.waitFor("document.querySelectorAll('[data-im=\"card\"]').length > " + before);
await sleep(700);
const idx = (await p.count('[data-im="card"]')) - 1;
console.log("new card idx", idx);
console.log("body click:", JSON.stringify(await p.box('[data-im="card"] [data-im="card-body"]', idx)));
await p.click('[data-im="card"] [data-im="card-body"]', idx).catch(e=>console.log("click body err", e.message));
await sleep(700);
console.log("editor after body click:", await p.exists('[data-im="card-editor"]'));
const host = await p.eval("(function(){ const h=document.querySelector('[data-im=\"card-toolbar-host\"]'); if(!h) return null; return { html: h.innerHTML.slice(0,1200), buttons: [...h.querySelectorAll('button')].map(b=>({im:b.getAttribute('data-im'), t:(b.textContent||'').trim().slice(0,10), w:Math.round(b.getBoundingClientRect().width)})) }; })()");
console.log("toolbar host:", JSON.stringify(host, null, 1).slice(0, 2200));
await b.close();
